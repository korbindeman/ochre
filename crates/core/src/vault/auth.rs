/// `POST {api}/two-factor/send-email-login` - triggers the login 2FA email.
/// Body is Bitwarden's `TwoFactorEmailRequestModel`: the account email, the
/// master-password hash (proves the first factor), and the device id.
fn send_email_request(
    config: &ServerConfig,
    email: &str,
    password_hash: &str,
    device_identifier: &str,
) -> HttpRequest {
    let body = format!(
        "{{\"email\":{},\"masterPasswordHash\":{},\"deviceIdentifier\":{}}}",
        json_string(email),
        json_string(password_hash),
        json_string(device_identifier),
    )
    .into_bytes();
    let mut headers = vec![
        ("Content-Type".to_string(), "application/json".to_string()),
        ("Accept".to_string(), "application/json".to_string()),
    ];
    headers.extend(client_headers());
    HttpRequest::post(
        format!("{}/two-factor/send-email-login", config.api_url),
        headers,
        body,
    )
}

// --- Token / login -----------------------------------------------------------

/// Client-identity headers required on **every** vault request. Both Bitwarden
/// cloud and Vaultwarden reject requests missing `Bitwarden-Client-Version`, so
/// this is appended by every request builder in the vault (auth, sync, import).
pub(crate) fn client_headers() -> Vec<(String, String)> {
    vec![
        ("Bitwarden-Client-Name".to_string(), CLIENT_NAME.to_string()),
        (
            "Bitwarden-Client-Version".to_string(),
            CLIENT_VERSION.to_string(),
        ),
    ]
}

fn token_headers(email: Option<&str>) -> Vec<(String, String)> {
    let mut headers = vec![
        (
            "Content-Type".to_string(),
            "application/x-www-form-urlencoded".to_string(),
        ),
        ("Accept".to_string(), "application/json".to_string()),
    ];
    // bitwarden.com expects the login email echoed as a base64url header.
    if let Some(email) = email {
        headers.push((
            "Auth-Email".to_string(),
            URL_SAFE_NO_PAD.encode(email.as_bytes()),
        ));
    }
    headers.extend(client_headers());
    headers
}

fn token_request(
    config: &ServerConfig,
    creds: &Credentials,
    device: &Device,
    password_hash: &str,
    two_factor: Option<&TwoFactor>,
) -> HttpRequest {
    let device_type = device.device_type.to_string();
    let mut fields: Vec<(&str, &str)> = vec![
        ("deviceType", &device_type),
        ("deviceIdentifier", &device.identifier),
        ("deviceName", &device.name),
    ];

    let provider_int;
    let remember;
    match &creds.grant {
        Grant::Password => {
            fields.push(("grant_type", "password"));
            fields.push(("scope", "api offline_access"));
            fields.push(("client_id", CLIENT_ID));
            fields.push(("username", &creds.email));
            fields.push(("password", password_hash));
        }
        Grant::ApiKey {
            client_id,
            client_secret,
        } => {
            fields.push(("grant_type", "client_credentials"));
            fields.push(("scope", "api"));
            fields.push(("client_id", client_id));
            fields.push(("client_secret", client_secret));
        }
    }

    if let Some(tf) = two_factor {
        provider_int = tf.provider.to_int().to_string();
        remember = if tf.remember { "1" } else { "0" };
        fields.push(("twoFactorToken", &tf.token));
        fields.push(("twoFactorProvider", &provider_int));
        fields.push(("twoFactorRemember", remember));
    }

    HttpRequest::post(
        format!("{}/connect/token", config.identity_url),
        token_headers(Some(&creds.email)),
        form_body(&fields),
    )
}

#[derive(Deserialize, Debug)]
struct TokenSuccess {
    access_token: String,
    #[serde(default)]
    refresh_token: String,
    #[serde(default)]
    expires_in: u64,
    /// The protected user key (an `EncString`). Absent on refresh responses.
    #[serde(rename = "Key", alias = "key", default)]
    key: Option<String>,
}

/// A `connect/token` error body. Bitwarden uses PascalCase historically and
/// camelCase in newer builds - accept both.
#[derive(Deserialize, Default)]
struct TokenError {
    #[serde(default)]
    error: Option<String>,
    #[serde(default)]
    error_description: Option<String>,
    #[serde(rename = "ErrorModel", alias = "errorModel", default)]
    error_model: Option<ErrorModel>,
    #[serde(rename = "TwoFactorProviders2", alias = "twoFactorProviders2", default)]
    two_factor_providers2: Option<std::collections::HashMap<String, serde_json::Value>>,
    #[serde(rename = "TwoFactorProviders", alias = "twoFactorProviders", default)]
    two_factor_providers: Option<Vec<serde_json::Value>>,
}

#[derive(Deserialize, Default)]
struct ErrorModel {
    #[serde(rename = "Message", alias = "message", default)]
    message: Option<String>,
}

fn parse_token_response(status: u16, body: &[u8]) -> Result<TokenSuccess, AuthError> {
    if is_success(status) {
        return serde_json::from_slice(body).map_err(|e| AuthError::Parse(format!("token: {e}")));
    }

    // Non-2xx: distinguish a 2FA challenge from a real credential failure.
    let err: TokenError = serde_json::from_slice(body).unwrap_or_default();

    if let Some(providers) = two_factor_providers(&err) {
        if !providers.is_empty() {
            return Err(AuthError::TwoFactorRequired(providers));
        }
    }

    let message = err
        .error_model
        .and_then(|m| m.message)
        .or(err.error_description)
        .or(err.error)
        .unwrap_or_else(|| format!("HTTP {status}"));

    // A 400 invalid_grant is a bad password; other statuses are server errors.
    if status == 400 {
        Err(AuthError::InvalidCredentials(message))
    } else {
        Err(AuthError::Server { status, message })
    }
}

/// Extract the offered 2FA providers from an error body, from either the
/// map-keyed (`TwoFactorProviders2`) or list (`TwoFactorProviders`) form.
fn two_factor_providers(err: &TokenError) -> Option<Vec<TwoFactorProvider>> {
    if let Some(map) = &err.two_factor_providers2 {
        return Some(
            map.keys()
                .filter_map(|k| k.parse::<u32>().ok())
                .map(TwoFactorProvider::from_int)
                .collect(),
        );
    }
    if let Some(list) = &err.two_factor_providers {
        return Some(
            list.iter()
                .filter_map(provider_value_to_int)
                .map(TwoFactorProvider::from_int)
                .collect(),
        );
    }
    None
}

/// A provider id in the list form may be a JSON number or a numeric string.
fn provider_value_to_int(v: &serde_json::Value) -> Option<u32> {
    v.as_u64()
        .map(|n| n as u32)
        .or_else(|| v.as_str().and_then(|s| s.parse().ok()))
}

// --- Small helpers -----------------------------------------------------------

fn is_success(status: u16) -> bool {
    (200..300).contains(&status)
}

fn server_error(status: u16, body: &[u8]) -> AuthError {
    let message = String::from_utf8_lossy(body).trim().to_string();
    AuthError::Server {
        status,
        message: if message.is_empty() {
            format!("HTTP {status}")
        } else {
            message
        },
    }
}

/// `application/x-www-form-urlencoded` body (percent-encodes `+`/`/`/`=` in the
/// base64 password hash - a hand-rolled encoder would get this wrong).
fn form_body(fields: &[(&str, &str)]) -> Vec<u8> {
    form_urlencoded::Serializer::new(String::new())
        .extend_pairs(fields.iter().copied())
        .finish()
        .into_bytes()
}

/// Minimal JSON string escaping for the one field (email) we emit as JSON.
fn json_string(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 => out.push_str(&format!("\\u{:04x}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// A random UUIDv4 string, from the OS RNG (avoids a `uuid` dependency).
fn uuid_v4() -> String {
    let mut b = [0u8; 16];
    // Device id uniqueness is not security-critical; an RNG failure is vanishingly
    // rare, and a zero-filled fallback still yields a well-formed, usable id.
    let _ = getrandom::getrandom(&mut b);
    b[6] = (b[6] & 0x0f) | 0x40; // version 4
    b[8] = (b[8] & 0x3f) | 0x80; // variant 1
    format!(
        "{:02x}{:02x}{:02x}{:02x}-{:02x}{:02x}-{:02x}{:02x}-{:02x}{:02x}-{:02x}{:02x}{:02x}{:02x}{:02x}{:02x}",
        b[0], b[1], b[2], b[3], b[4], b[5], b[6], b[7], b[8], b[9], b[10], b[11], b[12], b[13], b[14], b[15]
    )
}

