    #[test]
    fn uuid_v4_is_well_formed() {
        let id = uuid_v4();
        assert_eq!(id.len(), 36);
        let parts: Vec<&str> = id.split('-').collect();
        assert_eq!(
            parts.iter().map(|p| p.len()).collect::<Vec<_>>(),
            vec![8, 4, 4, 4, 12]
        );
        assert_eq!(&parts[2][..1], "4", "version nibble");
        assert!(
            matches!(&parts[3][..1], "8" | "9" | "a" | "b"),
            "variant nibble"
        );
        assert!(id.chars().all(|c| c.is_ascii_hexdigit() || c == '-'));
    }

    /// The payoff: a full prelogin→token→decrypt round-trip whose `Key` fixture
    /// is produced by the real crypto, proving P2-8 and P2-9 compose.
    #[test]
    fn login_unlocks_the_vault_end_to_end() {
        let email = "vault@example.com";
        let password = "hunter2";
        let kdf = Kdf::Pbkdf2 {
            iterations: 100_000,
        };

        // Server-side: protect a known vault key with the stretched master key.
        let master = MasterKey::derive(password, email, kdf).unwrap();
        let stretched = master.stretch().unwrap();
        let mut vault_bytes = [0u8; 64];
        for (i, b) in vault_bytes.iter_mut().enumerate() {
            *b = (i as u8).wrapping_mul(3);
        }
        let protected_key = stretched.encrypt(&vault_bytes).unwrap().to_string();

        let prelogin_body = r#"{"kdf":0,"kdfIterations":100000}"#.to_string();
        let token_body = format!(
            r#"{{"access_token":"at","refresh_token":"rt","expires_in":3600,"Key":"{protected_key}"}}"#
        );
        let transport = MockTransport::new(vec![ok(&prelogin_body), ok(&token_body)]);
        let client = VaultClient::new(transport, ServerConfig::bitwarden_cloud());

        let creds = Credentials {
            email: email.to_string(),
            master_password: Zeroizing::new(password.to_string()),
            grant: Grant::Password,
        };
        let session = client
            .login(&creds, &Device::generate("browser"), None)
            .unwrap();

        assert_eq!(session.tokens.access_token, "at");
        assert_eq!(session.tokens.expires_in, 3600);
        // The unlocked user key must be the one the "server" protected: it
        // decrypts what that exact key encrypts.
        let expected = SymmetricKey::from_bytes(&vault_bytes).unwrap();
        let cipher = expected.encrypt(b"https://site.example|user|pass").unwrap();
        assert_eq!(
            session.user_key.decrypt(&cipher).unwrap(),
            b"https://site.example|user|pass"
        );
    }

