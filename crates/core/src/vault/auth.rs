    #[test]
    fn token_request_password_grant_form_and_headers() {
        let cfg = ServerConfig::bitwarden_cloud();
        let creds = Credentials {
            email: "user@example.com".to_string(),
            master_password: Zeroizing::new("pw".to_string()),
            grant: Grant::Password,
        };
        let device = Device::with_identifier("dev-123".to_string(), "browser");
        // A hash containing base64 specials that MUST be percent-encoded.
        let req = token_request(&cfg, &creds, &device, "AB+/cd=", None);

        assert_eq!(req.url, "https://identity.bitwarden.com/connect/token");
        assert_eq!(field(&req.body, "grant_type").as_deref(), Some("password"));
        assert_eq!(field(&req.body, "client_id").as_deref(), Some("cli"));
        assert_eq!(
            field(&req.body, "username").as_deref(),
            Some("user@example.com")
        );
        assert_eq!(
            field(&req.body, "scope").as_deref(),
            Some("api offline_access")
        );
        assert_eq!(
            field(&req.body, "deviceIdentifier").as_deref(),
            Some("dev-123")
        );
        assert_eq!(field(&req.body, "deviceType").as_deref(), Some("7"));
        // The password round-trips through form decoding despite +, /, =.
        assert_eq!(field(&req.body, "password").as_deref(), Some("AB+/cd="));
        // Raw body must have escaped the specials, not left them literal.
        let raw = String::from_utf8(req.body.clone()).unwrap();
        assert!(
            raw.contains("password=AB%2B%2Fcd%3D"),
            "specials not escaped: {raw}"
        );
        // Auth-Email header present and base64url of the email.
        let auth_email = req
            .headers
            .iter()
            .find(|(k, _)| k == "Auth-Email")
            .map(|(_, v)| v.clone());
        assert_eq!(auth_email.as_deref(), Some("dXNlckBleGFtcGxlLmNvbQ"));
        // The client-version header the server now requires must be present.
        let client_version = req
            .headers
            .iter()
            .find(|(k, _)| k == "Bitwarden-Client-Version")
            .map(|(_, v)| v.clone());
        assert_eq!(client_version.as_deref(), Some(CLIENT_VERSION));
    }

