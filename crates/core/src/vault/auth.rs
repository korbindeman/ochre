    #[test]
    fn login_with_wrong_password_fails_at_key_decrypt() {
        // The token succeeds, but the protected key was encrypted under a
        // *different* master password, so unwrap must fail as invalid creds.
        let other = MasterKey::derive(
            "the-real-password",
            "vault@example.com",
            Kdf::Pbkdf2 {
                iterations: 100_000,
            },
        )
        .unwrap()
        .stretch()
        .unwrap();
        let protected_key = other.encrypt(&[7u8; 64]).unwrap().to_string();
        let token_body = format!(
            r#"{{"access_token":"at","refresh_token":"rt","expires_in":1,"Key":"{protected_key}"}}"#
        );
        let transport = MockTransport::new(vec![
            ok(r#"{"kdf":0,"kdfIterations":100000}"#),
            ok(&token_body),
        ]);
        let client = VaultClient::new(transport, ServerConfig::bitwarden_cloud());
        let creds = Credentials {
            email: "vault@example.com".to_string(),
            master_password: Zeroizing::new("wrong-password".to_string()),
            grant: Grant::Password,
        };
        assert!(matches!(
            client.login(&creds, &Device::generate("browser"), None),
            Err(AuthError::InvalidCredentials(_))
        ));
    }

    #[test]
    fn refresh_exchanges_the_refresh_token() {
        let transport = MockTransport::new(vec![ok(
            r#"{"access_token":"at2","refresh_token":"rt2","expires_in":3600}"#,
        )]);
        let client = VaultClient::new(transport, ServerConfig::bitwarden_cloud());
        let tokens = client.refresh("rt1").unwrap();
        assert_eq!(tokens.access_token, "at2");
        assert_eq!(tokens.refresh_token, "rt2");
        // The request carried the refresh grant.
        let sent = &client.transport.last_request();
        assert_eq!(
            field(&sent.body, "grant_type").as_deref(),
            Some("refresh_token")
        );
        assert_eq!(field(&sent.body, "refresh_token").as_deref(), Some("rt1"));
    }
