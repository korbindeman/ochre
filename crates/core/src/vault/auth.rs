//! Bitwarden vault auth / login (ADR-0016, spec §10).
//!
//! Turns a master password (or personal API key) into an **unlocked
//! [`Session`]**: the OAuth tokens plus the decrypted user [`SymmetricKey`] that
//! every cipher is encrypted under. The flow is Bitwarden's:
//!
//! 1. **prelogin** (`POST {identity}/accounts/prelogin`) → the account's [`Kdf`].
//! 2. derive the master key + master-password hash (see [`crate::vault::crypto`]).
//! 3. **token** (`POST {identity}/connect/token`) with the hash + a stable device
//!    identifier → tokens + the *protected* user key (an `EncString`).
//! 4. decrypt the protected key with the stretched master key → the user key.
//!
//! Two-factor (TOTP / YubiKey - not passkey/Duo as a *login* factor, per spec
//! §10) surfaces as [`AuthError::TwoFactorRequired`]; the caller re-invokes
//! [`VaultClient::login`] with a [`TwoFactor`].
//!
//! ## Testability
//!
//! Request-building, response-parsing, and error-mapping are pure functions,
//! unit-tested against fixtures + a mock transport (including a full
//! prelogin→token→decrypt round-trip whose `Key` fixture is generated by the
//! real crypto). What that can't prove - byte-exact endpoint paths / field
//! casing / client-id acceptance on a *live* server - is the manual
//! Vaultwarden validation this slice exists to enable (ADR-0016). The
//! server-facing constants below are the single place that pass tunes.

use crate::vault::crypto::{CryptoError, EncString, Kdf, MasterKey, SymmetricKey};
use crate::vault::http::{HttpRequest, HttpResponse, HttpTransport};
use base64::engine::general_purpose::URL_SAFE_NO_PAD;
use base64::Engine;
use serde::Deserialize;
use zeroize::Zeroizing;

// --- Server-facing constants (rbw-derived; validated against a live server) ---

/// OAuth client id for the interactive master-password grant. `cli` is rbw's
/// proven value; bitwarden.com may flag CLI-shaped traffic, which is exactly why
/// the API-key grant ([`Grant::ApiKey`]) exists (spec §10).
const CLIENT_ID: &str = "cli";
/// Client name/version echoed on every request. Bitwarden and Vaultwarden reject
/// requests without a `Bitwarden-Client-Version` header ("required to prevent
/// encryption errors"); the server only checks it is present and parses as a
/// version at or above its per-client minimum, so a recent CLI version is safe.
/// `cli` matches [`CLIENT_ID`]. Bump both here - the single place that pass tunes.
const CLIENT_NAME: &str = "cli";
const CLIENT_VERSION: &str = "2025.12.0";
/// Bitwarden `DeviceType.MacOsDesktop`.
const DEVICE_TYPE_MACOS: u32 = 7;
/// Default Argon2id parameters if prelogin omits them (Bitwarden's defaults).
const ARGON2_DEFAULT_MEMORY_KIB: u32 = 64 * 1024;
const ARGON2_DEFAULT_PARALLELISM: u32 = 4;

/// Where the vault lives. Bitwarden cloud splits identity/api across hosts;
/// self-hosted Vaultwarden serves both under one base.
#[derive(Debug, Clone)]
pub struct ServerConfig {
    /// Identity host, no trailing slash (prelogin + token live here).
    pub identity_url: String,
    /// API host, no trailing slash (sync lives here - used by the next slice).
    pub api_url: String,
}

impl ServerConfig {
    /// bitwarden.com.
    pub fn bitwarden_cloud() -> Self {
        Self {
            identity_url: "https://identity.bitwarden.com".to_string(),
            api_url: "https://api.bitwarden.com".to_string(),
        }
    }

    /// A self-hosted Vaultwarden / Bitwarden at `base` (e.g. `https://vault.example.com`).
    pub fn self_hosted(base: &str) -> Self {
        let base = base.trim_end_matches('/');
        Self {
            identity_url: format!("{base}/identity"),
            api_url: format!("{base}/api"),
        }
    }

    /// Resolve a user-entered server field into a config. **Empty ⇒ the default
    /// Bitwarden cloud** (bitwarden.com - the no-URL path); an official
    /// bitwarden.com host is also routed to the canonical split identity/api
    /// cloud config; anything else is a [`self_hosted`](Self::self_hosted)
    /// Vaultwarden/Bitwarden at that base.
    pub fn for_input(server: &str) -> Self {
        let s = server.trim().trim_end_matches('/');
        if s.is_empty() || is_bitwarden_cloud_host(s) {
            Self::bitwarden_cloud()
        } else {
            Self::self_hosted(s)
        }
    }
}

/// Whether `server` (a URL or bare host) points at bitwarden.com's cloud, whose
/// identity/api live on dedicated hosts rather than under a `/identity` path.
fn is_bitwarden_cloud_host(server: &str) -> bool {
    let host = server
        .split_once("://")
        .map_or(server, |(_, rest)| rest)
        .split('/')
        .next()
        .unwrap_or("")
        .to_ascii_lowercase();
    matches!(
        host.as_str(),
        "bitwarden.com" | "vault.bitwarden.com" | "identity.bitwarden.com" | "api.bitwarden.com"
    )
}

/// How to authenticate. Both still need the master password for *crypto* - the
/// grant only decides how the token endpoint authenticates.
#[derive(Debug, Clone)]
pub enum Grant {
    /// Interactive master-password login.
    Password,
    /// Personal API key (`client_credentials`) - avoids CLI-traffic flagging and
    /// interactive 2FA (spec §10).
    ApiKey {
        client_id: String,
        client_secret: String,
    },
}

/// Everything needed to unlock a vault. The master password is the crown jewel
/// (it re-derives every key and authenticates), so it is held in a
/// [`Zeroizing`] buffer that wipes the plaintext from heap on drop rather than
/// leaving it in freed memory for a core dump / swap leak to recover.
#[derive(Debug, Clone)]
pub struct Credentials {
    pub email: String,
    pub master_password: Zeroizing<String>,
    pub grant: Grant,
}

/// A stable device identity. Bitwarden keys sessions and "new device" emails to
/// this; it must persist across launches (that persistence is P2-11's job).
#[derive(Debug, Clone)]
pub struct Device {
    pub identifier: String,
    pub name: String,
    pub device_type: u32,
}

impl Device {
    /// A fresh device with a random UUIDv4 identifier.
    pub fn generate(name: &str) -> Self {
        Self {
            identifier: uuid_v4(),
            name: name.to_string(),
            device_type: DEVICE_TYPE_MACOS,
        }
    }

    /// Reconstruct from a persisted identifier.
    pub fn with_identifier(identifier: String, name: &str) -> Self {
        Self {
            identifier,
            name: name.to_string(),
            device_type: DEVICE_TYPE_MACOS,
        }
    }
}

/// A two-factor login provider (the int is Bitwarden's `TwoFactorProviderType`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TwoFactorProvider {
    Authenticator,
    Email,
    YubiKey,
    Duo,
    Other(u32),
}

impl TwoFactorProvider {
    fn from_int(n: u32) -> Self {
        match n {
            0 => Self::Authenticator,
            1 => Self::Email,
            3 => Self::YubiKey,
            4 => Self::Duo,
            other => Self::Other(other),
        }
    }

    fn to_int(self) -> u32 {
        match self {
            Self::Authenticator => 0,
            Self::Email => 1,
            Self::YubiKey => 3,
            Self::Duo => 4,
            Self::Other(n) => n,
        }
    }

    /// A stable, UI-facing tag for this provider. It crosses the FFI as the
    /// *kind* of a two-factor challenge so the native UI can show the right copy
    /// (and, for `email`, a Resend affordance) without knowing Bitwarden's ints.
    pub fn tag(self) -> &'static str {
        match self {
            Self::Authenticator => "authenticator",
            Self::Email => "email",
            Self::YubiKey => "yubikey",
            Self::Duo => "duo",
            Self::Other(_) => "other",
        }
    }

    /// Parse a [`tag`](Self::tag) back into a provider (`None` for unknown tags).
    pub fn from_tag(tag: &str) -> Option<Self> {
        match tag {
            "authenticator" => Some(Self::Authenticator),
            "email" => Some(Self::Email),
            "yubikey" => Some(Self::YubiKey),
            "duo" => Some(Self::Duo),
            _ => None,
        }
    }
}

/// A completed two-factor challenge to resubmit with the login.
#[derive(Debug, Clone)]
pub struct TwoFactor {
    pub provider: TwoFactorProvider,
    pub token: String,
    /// Ask the server to remember this device so future logins skip 2FA.
    pub remember: bool,
}

/// OAuth tokens. Expiry *policy* (when to refresh) is the session/cache slice's
/// job (P2-11); this carries the raw grant.
#[derive(Debug, Clone)]
pub struct Tokens {
    pub access_token: String,
    pub refresh_token: String,
    pub expires_in: u64,
}

/// An unlocked vault: tokens to talk to the API + the decrypted user key, plus
/// the bits the cache needs to re-derive that key on a later offline unlock (the
/// account email, its KDF, and the still-encrypted *protected* key).
pub struct Session {
    pub tokens: Tokens,
    pub user_key: SymmetricKey,
    pub kdf: Kdf,
    pub email: String,
    /// The wrapped user key (an `EncString`) exactly as the server sent it - safe
    /// at rest (decryptable only with the master password), so the cache stores it.
    pub protected_key: String,
}

/// Everything that can go wrong logging in.
#[derive(Debug)]
pub enum AuthError {
    /// Network / TLS / connection failure (not an HTTP error status).
    Transport(String),
    /// A response could not be parsed into the expected shape.
    Parse(String),
    /// The server needs a second factor before it will issue tokens.
    TwoFactorRequired(Vec<TwoFactorProvider>),
    /// Wrong email / password / API key (or the vault key would not decrypt).
    InvalidCredentials(String),
    /// An HTTP error the flow doesn't model specifically.
    Server { status: u16, message: String },
    /// A crypto step (KDF, key unwrap) failed.
    Crypto(CryptoError),
}

impl std::fmt::Display for AuthError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            AuthError::Transport(m) => write!(f, "transport error: {m}"),
            AuthError::Parse(m) => write!(f, "parse error: {m}"),
            AuthError::TwoFactorRequired(p) => write!(f, "two-factor required: {p:?}"),
            AuthError::InvalidCredentials(m) => write!(f, "invalid credentials: {m}"),
            AuthError::Server { status, message } => write!(f, "server error {status}: {message}"),
            AuthError::Crypto(e) => write!(f, "crypto error: {e}"),
        }
    }
}

impl std::error::Error for AuthError {}

/// A vault client bound to a transport + server. Blocking; call off the UI thread.
pub struct VaultClient<T: HttpTransport> {
    // `pub(crate)` so sibling modules (e.g. `sync`) can add client operations.
    pub(crate) transport: T,
    pub(crate) config: ServerConfig,
}

impl<T: HttpTransport> VaultClient<T> {
    pub fn new(transport: T, config: ServerConfig) -> Self {
        Self { transport, config }
    }

    /// Log in and unlock: prelogin → derive → token → decrypt the vault key.
    pub fn login(
        &self,
        creds: &Credentials,
        device: &Device,
        two_factor: Option<&TwoFactor>,
    ) -> Result<Session, AuthError> {
        let kdf = self.prelogin(&creds.email)?;

        let master_key = MasterKey::derive(&creds.master_password, &creds.email, kdf)
            .map_err(AuthError::Crypto)?;
        let password_hash = master_key.password_hash(&creds.master_password);

        let request = token_request(&self.config, creds, device, &password_hash, two_factor);
        let response = self.send(request)?;
        let success = parse_token_response(response.status, &response.body)?;

        let protected_key = success
            .key
            .ok_or_else(|| AuthError::Parse("token response missing protected key".to_string()))?;
        let protected = EncString::parse(&protected_key).map_err(AuthError::Crypto)?;
        let stretched = master_key.stretch().map_err(AuthError::Crypto)?;
        let user_key = stretched.unwrap_key(&protected).map_err(|_| {
            AuthError::InvalidCredentials(
                "could not decrypt the vault key (wrong master password?)".to_string(),
            )
        })?;

        Ok(Session {
            tokens: Tokens {
                access_token: success.access_token,
                refresh_token: success.refresh_token,
                expires_in: success.expires_in,
            },
            user_key,
            kdf,
            email: creds.email.clone(),
            protected_key,
        })
    }

    /// Ask the server to email a login two-factor code (Bitwarden
    /// `send-email-login`). This is required for the **Email** provider: unlike
    /// TOTP/YubiKey (where the code lives on the user's device), the server only
    /// dispatches the email when the client explicitly requests it. Call this
    /// after a [`AuthError::TwoFactorRequired`] that offers [`TwoFactorProvider::Email`];
    /// the user then re-invokes [`login`](Self::login) with the emailed code.
    pub fn send_email_login(&self, creds: &Credentials, device: &Device) -> Result<(), AuthError> {
        let kdf = self.prelogin(&creds.email)?;
        let master_key = MasterKey::derive(&creds.master_password, &creds.email, kdf)
            .map_err(AuthError::Crypto)?;
        let password_hash = master_key.password_hash(&creds.master_password);
        let request = send_email_request(
            &self.config,
            &creds.email,
            &password_hash,
            &device.identifier,
        );
        let response = self.send(request)?;
        if is_success(response.status) {
            Ok(())
        } else {
            Err(server_error(response.status, &response.body))
        }
    }

    /// Exchange a refresh token for a fresh access token.
    pub fn refresh(&self, refresh_token: &str) -> Result<Tokens, AuthError> {
        let form = form_body(&[
            ("grant_type", "refresh_token"),
            ("refresh_token", refresh_token),
            ("client_id", CLIENT_ID),
        ]);
        let request = HttpRequest::post(
            format!("{}/connect/token", self.config.identity_url),
            token_headers(None),
            form,
        );
        let response = self.send(request)?;
        let success = parse_token_response(response.status, &response.body)?;
        Ok(Tokens {
            access_token: success.access_token,
            refresh_token: success.refresh_token,
            expires_in: success.expires_in,
        })
    }

    fn prelogin(&self, email: &str) -> Result<Kdf, AuthError> {
        let response = self.send(prelogin_request(&self.config, email))?;
        parse_prelogin(response.status, &response.body)
    }

    fn send(&self, request: HttpRequest) -> Result<HttpResponse, AuthError> {
        self.transport
            .send(request)
            .map_err(|e| AuthError::Transport(e.0))
    }
}

// --- Prelogin ----------------------------------------------------------------

fn prelogin_request(config: &ServerConfig, email: &str) -> HttpRequest {
    let body = format!("{{\"email\":{}}}", json_string(email)).into_bytes();
    let mut headers = vec![
        ("Content-Type".to_string(), "application/json".to_string()),
        ("Accept".to_string(), "application/json".to_string()),
    ];
    headers.extend(client_headers());
    HttpRequest::post(
        format!("{}/accounts/prelogin", config.identity_url),
        headers,
        body,
    )
}

#[derive(Deserialize)]
struct PreloginResponse {
    #[serde(rename = "kdf", alias = "Kdf")]
    kdf: u32,
    #[serde(rename = "kdfIterations", alias = "KdfIterations")]
    kdf_iterations: u32,
    #[serde(rename = "kdfMemory", alias = "KdfMemory", default)]
    kdf_memory: Option<u32>,
    #[serde(rename = "kdfParallelism", alias = "KdfParallelism", default)]
    kdf_parallelism: Option<u32>,
}

fn parse_prelogin(status: u16, body: &[u8]) -> Result<Kdf, AuthError> {
    if !is_success(status) {
        return Err(server_error(status, body));
    }
    let p: PreloginResponse =
        serde_json::from_slice(body).map_err(|e| AuthError::Parse(format!("prelogin: {e}")))?;
    match p.kdf {
        0 => Ok(Kdf::Pbkdf2 {
            iterations: p.kdf_iterations,
        }),
        1 => Ok(Kdf::Argon2id {
            iterations: p.kdf_iterations,
            memory_kib: p.kdf_memory.unwrap_or(ARGON2_DEFAULT_MEMORY_KIB),
            parallelism: p.kdf_parallelism.unwrap_or(ARGON2_DEFAULT_PARALLELISM),
        }),
        other => Err(AuthError::Parse(format!("unknown KDF type {other}"))),
    }
}

