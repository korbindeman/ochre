    fn parse_prelogin_pbkdf2_and_argon2_and_casing() {
        assert_eq!(
            parse_prelogin(200, br#"{"kdf":0,"kdfIterations":600000}"#).unwrap(),
            Kdf::Pbkdf2 {
                iterations: 600_000
            }
        );
        // Argon2 with explicit params.
        assert_eq!(
            parse_prelogin(
                200,
                br#"{"kdf":1,"kdfIterations":3,"kdfMemory":19,"kdfParallelism":2}"#
            )
            .unwrap(),
            Kdf::Argon2id {
                iterations: 3,
                memory_kib: 19,
                parallelism: 2
            }
        );
        // Argon2 falling back to defaults, PascalCase field names accepted.
        assert_eq!(
            parse_prelogin(200, br#"{"Kdf":1,"KdfIterations":3}"#).unwrap(),
            Kdf::Argon2id {
                iterations: 3,
                memory_kib: ARGON2_DEFAULT_MEMORY_KIB,
                parallelism: ARGON2_DEFAULT_PARALLELISM,
            }
        );
    }

