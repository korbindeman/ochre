#!/usr/bin/env python3
"""Product identity - apply and check `product.toml` (ADR-0060).

`product.toml` is the source of truth for the user-facing name. This script
writes the generated Rust/Swift constants and patches `project.yml`, and
asserts that live surfaces still match. Code identifiers (`browser-core`,
`BrowserState`, Xcode scheme `Browser`) are out of scope.

Usage:
  scripts/product.py name
  scripts/product.py name-dev
  scripts/product.py bundle-id
  scripts/product.py bundle-id-dev
  scripts/product.py profile-dirs
  scripts/product.py ips-prefixes
  scripts/product.py sync
  scripts/product.py check
"""

from __future__ import annotations

import re
import sys
from dataclasses import dataclass
from pathlib import Path


def repo_root() -> Path:
    return Path(__file__).resolve().parent.parent


@dataclass(frozen=True)
class Product:
    name: str
    dev_suffix: str
    bundle_id_prefix: str
    bundle_id_name: str
    legacy_names: tuple[str, ...]

    @property
    def name_dev(self) -> str:
        return f"{self.name}{self.dev_suffix}"

    @property
    def bundle_id(self) -> str:
        return f"{self.bundle_id_prefix}.{self.bundle_id_name}"

    @property
    def bundle_id_dev(self) -> str:
        return f"{self.bundle_id}.dev"

    def profile_dirs(self) -> list[str]:
        dirs = [self.name_dev, self.name]
        for legacy in self.legacy_names:
            if legacy == self.name:
                continue
            dirs.append(f"{legacy}{self.dev_suffix}")
            dirs.append(legacy)
        return dirs

    def ips_prefixes(self) -> list[str]:
        prefixes = [self.name, "browser"]
        for legacy in self.legacy_names:
            if legacy not in prefixes:
                prefixes.append(legacy)
        return prefixes


def _unquote(value: str) -> str:
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in {'"', "'"}:
        return value[1:-1]
    return value


def _parse_list(value: str) -> tuple[str, ...]:
    value = value.strip()
    if not (value.startswith("[") and value.endswith("]")):
        raise ValueError(f"expected a toml array, got {value!r}")
    inner = value[1:-1].strip()
    if not inner:
        return ()
    return tuple(_unquote(part) for part in inner.split(",") if part.strip())


def load_product(root: Path | None = None) -> Product:
    path = (root or repo_root()) / "product.toml"
    raw: dict[str, str] = {}
    lists: dict[str, tuple[str, ...]] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if not line or "=" not in line:
            continue
        key, val = line.split("=", 1)
        key = key.strip()
        val = val.strip()
        if val.startswith("["):
            lists[key] = _parse_list(val)
        else:
            raw[key] = _unquote(val)

    name = raw["name"]
    if not name or '"' in name or "\\" in name or "\n" in name:
        raise SystemExit(f"error: product name {name!r} is empty or contains quotes")

    return Product(
        name=name,
        dev_suffix=raw.get("dev_suffix", " Dev"),
        bundle_id_prefix=raw["bundle_id_prefix"],
        bundle_id_name=raw["bundle_id_name"],
        legacy_names=lists.get("legacy_names", ()),
    )


def rust_source(product: Product) -> str:
    legacy = ", ".join(f'"{n}"' for n in product.legacy_names)
    return f"""//! Product identity. Generated from `product.toml` by `scripts/product.py`.
//! Edit the toml and run `just sync-product`; do not edit this file by hand.
//! See ADR-0060.

/// User-facing product name (Finder, menu, window title, `.app` basename).
pub const NAME: &str = "{product.name}";

/// Debug-profile Application Support / Finder name so it does not collide with release.
pub const NAME_DEV: &str = "{product.name_dev}";

/// Release bundle identifier.
pub const BUNDLE_ID: &str = "{product.bundle_id}";

/// Debug bundle identifier.
pub const BUNDLE_ID_DEV: &str = "{product.bundle_id_dev}";

/// Previous product names. Profile dirs are migrated on first launch; crash
/// harvest still scans these.
pub const LEGACY_NAMES: &[&str] = &[{legacy}];

/// Cargo helper-bin stem (`browser Helper.app`). Not the product name; Apple
/// `.ips` reports for subprocesses still use this prefix.
pub const HELPER_STEM: &str = "browser";
"""


def swift_source(product: Product) -> str:
    return f"""import Foundation

/// Product identity. Generated from `product.toml` by `scripts/product.py`.
/// Edit the toml and run `just sync-product`; do not edit this file by hand.
/// See ADR-0060.
enum Product {{
    static let name = "{product.name}"
    static let nameDev = "{product.name_dev}"

    /// Menu / window title: the bundle name, falling back to the toml identity.
    static var displayName: String {{
        Bundle.main.object(forInfoDictionaryKey: "CFBundleName") as? String ?? name
    }}
}}
"""


def patch_project_yml(text: str, product: Product) -> str:
    lines = text.splitlines(keepends=True)
    section = None
    out: list[str] = []
    for line in lines:
        stripped = line.strip()
        if stripped.startswith("Debug:"):
            section = "Debug"
        elif stripped.startswith("Release:"):
            section = "Release"
        indent = line[: len(line) - len(line.lstrip())]
        if re.match(r"PRODUCT_NAME:\s+\S+", stripped):
            line = f"{indent}PRODUCT_NAME: {product.name}\n"
        elif stripped.startswith("PRODUCT_BUNDLE_IDENTIFIER:"):
            ident = product.bundle_id_dev if section == "Debug" else product.bundle_id
            line = f"{indent}PRODUCT_BUNDLE_IDENTIFIER: {ident}\n"
        elif stripped.startswith("INFOPLIST_KEY_CFBundleDisplayName:"):
            display = product.name_dev if section == "Debug" else product.name
            line = f"{indent}INFOPLIST_KEY_CFBundleDisplayName: {display}\n"
        out.append(line)
    return "".join(out)


def generated_paths(root: Path) -> dict[str, Path]:
    return {
        "rust": root / "crates" / "core" / "src" / "product.rs",
        "swift": root / "apps" / "macos" / "Sources" / "Product.swift",
        "project": root / "apps" / "macos" / "project.yml",
    }


def sync(root: Path) -> None:
    product = load_product(root)
    paths = generated_paths(root)
    paths["rust"].write_text(rust_source(product), encoding="utf-8")
    paths["swift"].write_text(swift_source(product), encoding="utf-8")
    project = paths["project"]
    project.write_text(patch_project_yml(project.read_text(encoding="utf-8"), product), encoding="utf-8")
    print(f"synced product identity: {product.name}")


def _read(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def check(root: Path) -> int:
    product = load_product(root)
    paths = generated_paths(root)
    errors: list[str] = []

    expected_rust = rust_source(product)
    actual_rust = _read(paths["rust"])
    if actual_rust != expected_rust:
        errors.append(f"{paths['rust'].relative_to(root)} is stale; run `just sync-product`")

    expected_swift = swift_source(product)
    actual_swift = _read(paths["swift"])
    if actual_swift != expected_swift:
        errors.append(f"{paths['swift'].relative_to(root)} is stale; run `just sync-product`")

    project = _read(paths["project"])
    patched = patch_project_yml(project, product)
    if project != patched:
        errors.append("apps/macos/project.yml product fields are stale; run `just sync-product`")

    if f"PRODUCT_NAME: {product.name}" not in project:
        errors.append(f"apps/macos/project.yml must set PRODUCT_NAME: {product.name}")

    leftovers = [
        ("justfile", "Browser.app"),
        ("scripts/install-dogfood.sh", "/Applications/Browser.app"),
        ("scripts/package-update-artifacts.sh", "Browser.app.tar.gz"),
        (".github/workflows/alpha-release.yml", "Browser.app"),
    ]
    for rel, needle in leftovers:
        text = _read(root / rel)
        if needle in text:
            errors.append(f"{rel} still hardcodes {needle!r}; derive the name from product.toml or the .app path")

    if errors:
        print("product-check failed:", file=sys.stderr)
        for err in errors:
            print(f"  {err}", file=sys.stderr)
        return 1
    print(f"product-check ok ({product.name})")
    return 0


def main(argv: list[str]) -> int:
    root = repo_root()
    cmd = argv[1] if len(argv) > 1 else "name"
    if cmd in {"-h", "--help", "help"}:
        print(__doc__.strip())
        return 0

    product = load_product(root)
    if cmd == "name":
        print(product.name)
    elif cmd == "name-dev":
        print(product.name_dev)
    elif cmd == "bundle-id":
        print(product.bundle_id)
    elif cmd == "bundle-id-dev":
        print(product.bundle_id_dev)
    elif cmd == "profile-dirs":
        print("\n".join(product.profile_dirs()))
    elif cmd == "ips-prefixes":
        print("\n".join(product.ips_prefixes()))
    elif cmd == "sync":
        sync(root)
    elif cmd == "check":
        return check(root)
    else:
        print(f"usage: {argv[0]} [name|name-dev|bundle-id|bundle-id-dev|profile-dirs|ips-prefixes|sync|check]", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
